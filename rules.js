// AU Acknowledgement Blocker - rules
//
// Each entry: which site, what to hide, what to click, what to unlock.
// Any field may be omitted.
//   unlock          - selectors that get `overflow:visible / height:auto /
//                     position:static / top:auto !important` injected.
//   reloadOnce      - the dialog's selector. When it matches (dialog has
//                     rendered), set a sessionStorage flag and reload the
//                     page once. Use for sites that store a "seen" cookie
//                     when the dialog renders, so the second load is
//                     dialog-free. Flag prevents reload loops. Name only the
//                     dialog: anything that renders earlier (e.g. a footer)
//                     reloads before the cookie is written.
//   setCookie       - { name: "value" } cookies to write at document_start
//                     before the site's JS reads them. Use for sites whose
//                     dismiss state is gated entirely on a cookie that we
//                     can spoof (e.g. heide's `hiaDismissed`).
//   removeText     - short quotes identifying text segments that have no
//                     element of their own (siblings split only by <br>).
//                     The matching text node is removed along with the <br>
//                     padding around it. Use only when no selector can isolate
//                     the text without taking content we need to keep.
//   setLocalStorage - { key: "value" } localStorage entries to write at
//                     document_start. Use for sites whose dismiss state is
//                     gated on localStorage (e.g. powerhouse's
//                     `power_fn_dismissed`).
//
// When adding a site, also add `*://<site>/*` and `*://*.<site>/*`
